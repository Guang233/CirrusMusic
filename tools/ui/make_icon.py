#!/usr/bin/env python3
"""Draw the Cirrus app icon and render its bitmaps.

Cirrus clouds at dusk: three wind-combed streaks, thin tails at the lower left and
round heads at the upper right, each a soft core in a bundle of fine fibres, over a
sky from indigo through violet to a warm horizon (chosen by the maintainer,
2026-11-10). The drawing is deterministic: edit it here and run this again; never
edit the outputs by hand.

Outputs (ui/app/icons/):
  cirrus.svg          the master (blur filters: needs a renderer with SVG filters)
  cirrus-<N>.png      N = 16 24 32 48 64 128 256 512 1024 (window, tray, packages)
  cirrus.ico          Windows (16–256)
The macOS .icns is made from the PNGs by iconutil when packaging.
Requires rsvg-convert (librsvg) and ImageMagick (magick).
"""

import math
import random
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "ui" / "app" / "icons"
SIZES = (16, 24, 32, 48, 64, 128, 256, 512, 1024)
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)


def bezier(p, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = p
    u = 1 - t
    return (u**3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x3,
            u**3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y3)


def ribbon(p, width, profile, offset=0.0, s0=0.0, s1=1.0, n=160):
    """A band along the curve `p` from s0 to s1, `width` shaped by `profile`; fibres
    sit `offset` beside it and spread out toward the tail, as the wind combs them."""
    left, right = [], []
    for i in range(n + 1):
        s = s0 + (s1 - s0) * i / n
        xa, ya = bezier(p, max(0.0, s - 1e-3))
        xb, yb = bezier(p, min(1.0, s + 1e-3))
        x, y = bezier(p, s)
        dx, dy = xb - xa, yb - ya
        length = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / length, dx / length
        off = offset * (0.5 + 0.5 * (1 - s))
        cx, cy = x + nx * off, y + ny * off
        w = width * profile((s - s0) / (s1 - s0)) / 2
        left.append((cx + nx * w, cy + ny * w))
        right.append((cx - nx * w, cy - ny * w))
    points = left + right[::-1]
    return "M" + " L".join(f"{a:.2f} {b:.2f}" for a, b in points) + " Z"


def blunt(s):  # thin tail, round head at s = 1
    return s * max(0.0, 1 - s) ** 0.35


def fibre(s):
    return s**0.7 * max(0.0, 1 - s) ** 0.5


# (curve from tail to head, head width, fibres)
STREAKS = (
    (((18, 180), (90, 152), (150, 98), (214, 80)), 40, 13),
    (((36, 216), (106, 198), (160, 152), (222, 140)), 27, 10),
    (((76, 244), (126, 232), (176, 202), (216, 194)), 17, 7),
)


def svg():
    rnd = random.Random(11)
    haze, fibres, cores = [], [], []
    for p, w, count in STREAKS:
        haze.append(f'<path d="{ribbon(p, w * 1.5, blunt, s0=0.15)}" opacity="0.35"/>')
        cores.append(f'<path d="{ribbon(p, w * 0.75, blunt, s0=0.05)}" opacity="0.95"/>')
        for j in range(count):
            off = (j - (count - 1) / 2) * w * 0.24 + rnd.uniform(-2, 2)
            a, b = rnd.uniform(0.0, 0.3), rnd.uniform(0.75, 0.97)
            fibres.append(f'<path d="{ribbon(p, rnd.uniform(2.6, 5.5), fibre, off, a, b)}" '
                          f'opacity="{rnd.uniform(0.3, 0.7):.2f}"/>')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
  <!-- Generated by tools/ui/make_icon.py; edit that, not this. -->
  <defs>
    <linearGradient id="sky" x1="0.35" y1="0" x2="0.6" y2="1">
      <stop offset="0" stop-color="#1F2A70"/>
      <stop offset="0.45" stop-color="#5A47B0"/>
      <stop offset="0.8" stop-color="#D98AAE"/>
      <stop offset="1" stop-color="#FFC79C"/>
    </linearGradient>
    <linearGradient id="cloud" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="1" stop-color="#FFE0CC"/>
    </linearGradient>
    <clipPath id="shape"><rect x="8" y="8" width="240" height="240" rx="60"/></clipPath>
    <filter id="haze" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="6"/></filter>
    <filter id="fibre" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="1.5"/></filter>
    <filter id="core" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="1.8"/></filter>
  </defs>
  <g clip-path="url(#shape)">
    <rect x="8" y="8" width="240" height="240" fill="url(#sky)"/>
    <g fill="url(#cloud)" filter="url(#haze)">{"".join(haze)}</g>
    <g fill="url(#cloud)" filter="url(#fibre)">{"".join(fibres)}</g>
    <g fill="url(#cloud)" filter="url(#core)">{"".join(cores)}</g>
  </g>
</svg>
'''


def main():
    for tool in ("rsvg-convert", "magick"):
        if not shutil.which(tool):
            sys.exit(f"{tool} not found")
    OUT.mkdir(parents=True, exist_ok=True)
    master = OUT / "cirrus.svg"
    master.write_text(svg(), encoding="utf-8")
    for size in SIZES:
        subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), str(master),
                        "-o", str(OUT / f"cirrus-{size}.png")], check=True)
    subprocess.run(["magick", *[str(OUT / f"cirrus-{s}.png") for s in ICO_SIZES],
                    str(OUT / "cirrus.ico")], check=True)
    print(f"wrote {master.relative_to(ROOT)}, {len(SIZES)} PNGs and cirrus.ico")


if __name__ == "__main__":
    main()
